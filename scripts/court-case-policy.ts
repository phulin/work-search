// A few catalogue entries are administrative bodies classified as trial or
// appellate courts. Preserve this explicit correction alongside the policy.
const NON_COURTS = new Set([
  "masstaxbd",
  "njlaborcomp",
  "njpuc",
  "nyhospcommn",
  "ohiopuc",
  "vamedmalrevpan",
]);
export function courtCaseDecision(
  id: string | null | undefined,
  court: { jurisdiction: string } | undefined,
) {
  if (!id || !court) return "unknown-court";
  if (NON_COURTS.has(id)) return "non-court";
  if (COURT_JURISDICTIONS.has(court.jurisdiction) || SPECIAL_COURTS.has(id))
    return "include";
  return "non-court";
}
